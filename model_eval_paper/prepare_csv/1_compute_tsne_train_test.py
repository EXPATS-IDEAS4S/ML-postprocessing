"""Compute t-SNE coordinates for a prepared feature dataset.

The input CSV is the merged dataset produced by
``0_prepare_feature_dataset.py``. Its path is derived from
``model_eval_paper/process_run_config.yaml`` (or a configuration path passed
with ``--config``). Every column whose name starts with ``dim_`` is used as a
feature dimension, including TRAIN, TEST, and CENTROID rows. The two resulting
coordinates are added to the same DataFrame and the input CSV is overwritten.

Examples
--------
Run with the project configuration::

    python 1_compute_tsne_train_test.py

Run with another configuration::

    python 1_compute_tsne_train_test.py --config /path/to/process_run_config.yaml
"""

import argparse
import logging
import os
import sys
import time
from pathlib import Path

import numpy as np
import openTSNE
import pandas as pd


REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))

from utils.configs import load_config


logger = logging.getLogger(__name__)


def configure_logging(config):
    """Configure timestamped console logging for the t-SNE run."""
    level_name = str(config.get("logging", {}).get("log_level", "INFO")).upper()
    logging.basicConfig(
        level=getattr(logging, level_name, logging.INFO),
        format="%(asctime)s | %(levelname)s | %(message)s",
    )


def resolve_input_csv(config):
    """Return the feature CSV path generated by script 0."""
    experiment = config["experiment"]
    preparation = config["feature_preparation"]
    run_name = experiment["run_names"][0]
    output_path = Path(experiment["path_out"]) / run_name / preparation.get(
        "output_suffix", "all"
    )
    filename = f"{preparation.get('output_filename', 'features')}_{run_name}.csv"
    return output_path / filename


def add_tsne_coordinates(df, reduction_config):
    """Compute two-dimensional t-SNE coordinates for all feature rows.

    Parameters
    ----------
    df : pandas.DataFrame
        Prepared feature dataset containing ``dim_*`` columns.
    reduction_config : dict
        Settings from the YAML ``reduction`` section.

    Returns
    -------
    pandas.DataFrame
        The original DataFrame with ``tsne_dim_1`` and ``tsne_dim_2`` added.
    """
    feature_columns = [column for column in df.columns if column.startswith("dim_")]
    if not feature_columns:
        raise ValueError("The input CSV does not contain any 'dim_*' feature columns.")

    features = df[feature_columns].to_numpy(dtype=np.float32)
    tsne = openTSNE.TSNE(
        n_components=2,
        perplexity=reduction_config.get("perplexity", 50),
        initialization="pca",
        metric=reduction_config.get("metric", "cosine"),
        random_state=reduction_config.get("random_state", 42),
        n_jobs=reduction_config.get("n_jobs", -1),
        verbose=True,
    )
    embedding = np.asarray(tsne.fit(features))
    df["tsne_dim_1"] = embedding[:, 0]
    df["tsne_dim_2"] = embedding[:, 1]
    return df


def main():
    """Load the configured feature CSV, add t-SNE columns, and overwrite it."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--config",
        type=Path,
        help="Path to the YAML configuration file (overrides PROCESS_RUN_CONFIG).",
    )
    args = parser.parse_args()

    config_path = args.config or Path(
        os.getenv(
            "PROCESS_RUN_CONFIG",
            str(REPO_ROOT / "model_eval_paper" / "process_run_config.yaml"),
        )
    )
    config = load_config(config_path)
    configure_logging(config)
    input_csv = resolve_input_csv(config)

    logger.info("Using configuration: %s", config_path)
    logger.info("Reading CSV file: %s", input_csv)
    df = pd.read_csv(input_csv, low_memory=False)
    logger.info(
        "Loaded CSV file: %s (%d rows, %d columns)",
        input_csv,
        len(df),
        len(df.columns),
    )
    feature_count = len([column for column in df.columns if column.startswith("dim_")])
    logger.info("Using %d feature dimensions", feature_count)
    logger.info("Computing t-SNE for %d vectors", len(df))

    reduction_config = dict(config.get("reduction", {}))
    reduction_config.setdefault(
        "random_state", config["experiment"].get("random_state", 42)
    )
    started = time.perf_counter()
    add_tsne_coordinates(df, reduction_config)
    logger.info("t-SNE completed in %.1f seconds", time.perf_counter() - started)
    df.to_csv(input_csv, index=False)
    logger.info("Overwrote feature dataset with t-SNE coordinates: %s", input_csv)


if __name__ == "__main__":
    main()